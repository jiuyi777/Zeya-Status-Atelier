import {readFile,writeFile} from 'node:fs/promises';
import {editorialize,buildEditorialAssets} from './reference-editorial.mjs';
const root=new URL('../',import.meta.url);
const catalog=JSON.parse(await readFile(new URL('assets/reference-status/catalog.json',root),'utf8'));
const names={'塞利安·维尔德':'当前角色','塞利安状态栏':'蓝金书摘','心华·状态':'歌笺小剧场','Xin Hua Status':'STORY STATUS','心华小剧场':'角色小剧场','心华状态栏':'歌笺小剧场','陆 临':'人物一','陆 昭':'人物二','陆临':'人物一','陆昭':'人物二','埃利奥斯':'人物一','卡厄斯':'人物二','泽夜 Zeye':'当前角色','塞尔的内心':'角色的内心','塞尔状态':'学习手记','程春状态栏':'蚀月唱机','沥城':'当前场景',"LIUYU'S STATUS":'STORY STATUS'};
for(const item of catalog){
 const source=JSON.parse(await readFile(new URL(item.sourceFile,root),'utf8'));
 if(item.id==='reference-wechat-night'){
  item.fields[0][1]='填写当前对话的联系人名称；未知写未明确';
  item.fields[2][1]='依据已有剧情填写聊天记录，每条消息单独一行，以“对方：”或“我：”标记发送方；没有发生的回复不要编造。单条无标记消息按对方消息显示';
 }
 item.lines=item.lines.map(([key,count])=>[({LuLinThought:'PersonOneThought',LuZhaoThought:'PersonTwoThought',AeliusThoughts:'PersonOneThoughts',AeliusPlan:'PersonOnePlan',KaosThoughts:'PersonTwoThoughts',KaosPlan:'PersonTwoPlan'})[key]||key,count]);
 let html=source.replaceString.trim().replace(/^```html\s*/i,'').replace(/\s*```$/,'');
 if(item.id==='reference-blue-gold')html=html.replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi,'');
 if(item.id==='reference-magic-note'){
  const template=html.match(/var html = `([\s\S]*?)`;/)?.[1];
  if(!template)throw Error('Missing magic note markup');
  const markup=template.replaceAll('${data.date}','$1').replaceAll('${data.time}','$2').replaceAll('${data.thought}','$3');
  html=html.replace(/<div\b[^>]*id="zeye-status-container"[^>]*>\s*<div class="zeye-error">[\s\S]*?<\/div>/,`<div class="zeye-status-wrapper" id="zeye-status-container">${markup}`)
   .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi,'<script>function toggleZeyeAccordion(element){element.parentElement.classList.toggle("zeye-collapsed")}</script>');
 }
 if(item.id==='reference-magazine'){
  // Plan values are plain text, including when they contain markup-like strings.
  html=html.replace('const planStr = parsedData[\'Plan\'] || \'\';',`const planStr = (parsedData['Plan'] || '').replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));`);
 }
 if(item.id==='reference-eclipse-player'){
  item.defaultPlaylist=[...html.matchAll(/'(https:\/\/[^']+\.(?:mp3|flac))'/g)].map(m=>m[1]);
  html=html.replace(/var playlist = \[[\s\S]*?\];/,'var playlist = window.staReferenceMedia.playlist;');
  // Keep playback user initiated and stop detached iframe audio.
  html=html.replace("audio.preload = 'metadata';","audio.preload = 'none'; window.staReferenceAudio=audio; window.addEventListener('pagehide',function(){audio.pause();audio.removeAttribute('src');audio.load()},{once:true});");
  html=html.replace('currentIndex = index;','if (!shuffled.length) { btnPlay.title="请先填写音乐链接"; return; } currentIndex = index;');
  html=html.replace('/* 浏览器可能阻止自动播放，用户点击后才能播放 */','btnPlay.title="音乐加载失败，请检查直链或重新点击播放"; btnPlay.setAttribute("aria-label",btnPlay.title);');
 }
 for(const [from,to] of Object.entries(names))html=html.replaceAll(from,to);
 // Correct the source declarations rather than layering another colored edge.
 html=html.replace(/border-left\s*:\s*[^;{}]+;/gi,'border-left:0;');
 html=html.replace(/scrollbar-width\s*:\s*(?:thin|auto)\s*;/gi,'scrollbar-width:none;');
 item.html=editorialize(html,item.id);
 item.avatarSelectors=item.id==='reference-wechat-night'?['.char-avatar','.user-avatar']:item.id==='reference-weibo'?['.wav[data-name]','.wstk-av[data-name]']:
  item.id==='reference-study-slime'?['.sel-avatar']:['.char-avatar','.user-avatar'].filter(sel=>html.includes(sel.slice(1)));
}
await writeFile(new URL('reference-status-data.js',root),'// Generated by scripts/build-reference-status.mjs; edit sources/catalog or builder.\nexport const REFERENCE_STATUS_DATA = '+JSON.stringify(catalog)+';\n');
const home=JSON.parse(await readFile(new URL('assets/reference-status/sources/social-home.json',root),'utf8'));
await writeFile(new URL('reference-home-data.js',root),'// Generated from user supplied homepage.\nexport const REFERENCE_HOME_SOURCE = '+JSON.stringify(editorialize(home.replaceString,'social-home'))+';\n');
await buildEditorialAssets();
console.log('REFERENCE_STATUS_BUILD_OK: '+catalog.length);
