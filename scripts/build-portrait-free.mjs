import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../status-portrait-free/', import.meta.url);
const read = name => readFile(new URL(name, root), 'utf8');
const templates = {};
for (const name of ['pixel-dream', 'earth-night', 'quiet-clock']) {
  let html = await read(`${name}.html`);
  for (const match of [...html.matchAll(/<link rel="stylesheet" href="([^"]+)">/g)]) {
    html = html.replace(match[0], `<style>${await read(match[1])}</style>`);
  }
  html = html.replace(/<script\b[^>]*src="[^"]+"[^>]*><\/script>/g, '');
  html = html.replace(/\b(src|href)="(assets|fonts)\//g, '$1="__STA_PORTRAIT_ASSETS__$2/')
    .replace(/url\(['"]?(assets|fonts)\//g, 'url("__STA_PORTRAIT_ASSETS__$1/')
    .replace(/(\.woff2|\.png|\.jpg|\.webp)'\)/g, '$1")');
  let runtime = `${await read('runtime.js')}\n${await read('tabs.js')}`;
  if (name !== 'pixel-dream') runtime += `\n${(await read(`${name}.js`)).replace(/^export /gm, '').replace(/(['"])assets\//g, '$1__STA_PORTRAIT_ASSETS__assets/')}`;
  // Sample names and values belong only to the gallery. Production is filled by the payload runtime.
  html = html.replace(/(<[^>]+data-field="[^"]+"[^>]*>)[^<]*/g, '$1')
    .replace(/(<nav[^>]+class="[^"]*people[^"]*"[^>]*>)[\s\S]*?<\/nav>/g, '$1</nav>');
  templates[name] = { html, runtime };
}
const source = `// Generated by scripts/build-portrait-free.mjs from status-portrait-free/.\nexport const PORTRAIT_FREE_TEMPLATES = ${JSON.stringify(templates, null, 2)};\n`;
const target = new URL('../status-portrait-free-templates.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== source) throw new Error('状态栏源文件变化后请运行 npm run build:portrait-free');
  console.log('PORTRAIT_FREE_BUILD_CURRENT');
} else {
  await writeFile(target, source);
  console.log(`Built three portrait-free templates: ${fileURLToPath(target)}`);
}
